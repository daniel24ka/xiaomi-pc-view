    val addCamera: String,
    val ipName: String,
    val ipUrl: String,
    val ipUrlHint: String,
    val rename: String,
    val remove: String,
    val removeAsk: String,
    val save: String,
    val close: String,
    val importDone: String,
    val error: String,
    val loading: String,
    val version: String,
) {
    fun nightMode(value: Int?): String = nightModes[value] ?: nightModeLabel
    fun point(n: Int) = pointN.format(n)
}

